"""**Walk-Forward Backtesting**"""

months_to_test = ["2025-10", "2025-11", "2025-12"]
forecast_months = forecast_power_df["time"].dt.tz_convert("Europe/Copenhagen").dt.strftime("%Y-%m")
test_start = forecast_power_df["time"].iloc[split_index]

walk_forward_results = []
walk_forward_predictions = []

for month in months_to_test:
    month_start = pd.Timestamp(month, tz="Europe/Copenhagen").tz_convert("UTC")
    test_mask = (forecast_months == month) & (forecast_power_df["time"] >= test_start)
    train_mask = forecast_power_df["time"] < max(month_start, test_start)

    wf_model = GradientBoostingRegressor(n_estimators=200, learning_rate=0.05, max_depth=2, random_state=42)
    wf_model.fit(X_forecast.loc[train_mask], y_forecast.loc[train_mask])
    actual = y_forecast.loc[test_mask]
    predictions = wf_model.predict(X_forecast.loc[test_mask])

    walk_forward_results.append([month, train_mask.sum(), test_mask.sum(), mean_absolute_error(actual, predictions), mean_squared_error(actual, predictions) ** 0.5, r2_score(actual, predictions)])
    walk_forward_predictions.append(pd.DataFrame({"Actual Generation": actual.values, "Predicted Generation": predictions}))

walk_forward_results_df = pd.DataFrame(walk_forward_results, columns=["Month", "Training Observations", "Testing Observations", "MAE", "RMSE", "R²"])
walk_forward_predictions_df = pd.concat(walk_forward_predictions, ignore_index=True)

display(walk_forward_results_df.round(3))

actual_all = walk_forward_predictions_df["Actual Generation"]
predicted_all = walk_forward_predictions_df["Predicted Generation"]

print("Overall MAE:", round(mean_absolute_error(actual_all, predicted_all), 3))
print("Overall RMSE:", round(mean_squared_error(actual_all, predicted_all) ** 0.5, 3))
print("Overall R²:", round(r2_score(actual_all, predicted_all), 3))

